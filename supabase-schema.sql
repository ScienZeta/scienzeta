-- ScienZeta starter database schema (Supabase / PostgreSQL)
-- Run this in Supabase Dashboard > SQL Editor.
-- IMPORTANT: Keep Row Level Security enabled. Create the first admin manually as described in README.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Student',
  role text not null default 'student' check (role in ('student','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.study_materials (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  category text not null default 'General',
  exam text not null default 'All',
  pdf_path text not null,
  is_published boolean not null default false,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  question text not null,
  options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) >= 2),
  correct_option integer not null check (correct_option >= 0),
  explanation text not null default '',
  category text not null default 'GK',
  exam text not null default 'All',
  is_published boolean not null default false,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  constraint correct_option_in_range check (correct_option < jsonb_array_length(options))
);

create table if not exists public.test_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  test_name text not null default 'GK Mini Test',
  score integer not null check (score >= 0),
  total_questions integer not null check (total_questions > 0 and score <= total_questions),
  answers jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists study_materials_published_idx on public.study_materials(is_published, created_at desc);
create index if not exists quiz_questions_published_idx on public.quiz_questions(is_published, category);
create index if not exists test_attempts_user_idx on public.test_attempts(user_id, created_at desc);

-- Keep a profile row for each newly registered user.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'display_name', 'Student'),
    'student'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.study_materials enable row level security;
alter table public.quiz_questions enable row level security;
alter table public.test_attempts enable row level security;

-- Profiles: users can read their own profile. No browser policy lets a user change their role.
drop policy if exists "Read own profile" on public.profiles;
create policy "Read own profile" on public.profiles
for select to authenticated using (id = (select auth.uid()) or public.is_admin());

drop policy if exists "Admin manage profiles" on public.profiles;
create policy "Admin manage profiles" on public.profiles
for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Public can read published notes and questions. Only admins can write/publish.
drop policy if exists "Read published materials" on public.study_materials;
create policy "Read published materials" on public.study_materials
for select to anon, authenticated using (is_published or public.is_admin());

drop policy if exists "Admin manage materials" on public.study_materials;
create policy "Admin manage materials" on public.study_materials
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Read published questions" on public.quiz_questions;
create policy "Read published questions" on public.quiz_questions
for select to anon, authenticated using (is_published or public.is_admin());

drop policy if exists "Admin manage questions" on public.quiz_questions;
create policy "Admin manage questions" on public.quiz_questions
for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- A student can insert and read only their own attempts. Admins can review all attempts.
drop policy if exists "Read own attempts" on public.test_attempts;
create policy "Read own attempts" on public.test_attempts
for select to authenticated using (user_id = (select auth.uid()) or public.is_admin());

drop policy if exists "Insert own attempts" on public.test_attempts;
create policy "Insert own attempts" on public.test_attempts
for insert to authenticated with check (user_id = (select auth.uid()));

drop policy if exists "Admin manage attempts" on public.test_attempts;
create policy "Admin manage attempts" on public.test_attempts
for all to authenticated using (public.is_admin()) with check (public.is_admin());

